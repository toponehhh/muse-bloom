'use strict';
// Derive UV fitting data from actual native garment pixels. Atlas artwork is
// retained intact; native coverage and neck/waist seams remain authoritative.
const fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
(async()=>{
  const source=JSON.parse(fs.readFileSync(path.join(__dirname,'capsule-source.json'),'utf8'));
  for(const fit of Object.values(source))fit.atlasUrl='data:image/webp;base64,'+fs.readFileSync(path.join(root,fit.asset)).toString('base64');
  const channel=process.env.MUSE_BROWSER_CHANNEL||(process.platform==='win32'?'msedge':'chromium');
  const browser=await chromium.launch({channel:channel==='chromium'?undefined:channel,headless:true});
  try {
    const page=await browser.newPage();
    await page.setContent('<!doctype html><body></body>');
    for(const name of ['data','art'])await page.addScriptTag({path:path.join(root,'js',name+'.js')});
    const targets=await page.evaluate(async source=>{
      const result={};
      for(const id of Object.keys(source)){
        const fit=source[id];
        const item=MuseData.items.find(i=>i.id===id);
        const svg=MuseArt.fittedItemSvg(item,true);
        const im=new Image();im.src=MuseArt.uri(svg);await im.decode();
        const c=document.createElement('canvas');c.width=720;c.height=1280;
        const ctx=c.getContext('2d');ctx.drawImage(im,0,0);
        const data=ctx.getImageData(0,0,720,1280).data;
        const row=y=>{let lo=720,hi=0;for(let x=0;x<720;x++)if(data[(Math.min(1279,Math.floor(y))*720+x)*4+3]>220){lo=Math.min(lo,x);hi=Math.max(hi,x+1);}return hi?[lo,hi]:null;};
        let top=1280,bottom=0,left=720,right=0;
        for(let y=0;y<1280;y++){const r=row(y);if(r){top=Math.min(top,y);bottom=y+1;left=Math.min(left,r[0]);right=Math.max(right,r[1]);}}
        const target=[left,top,right-left,bottom-top];
        const targetRows=Array.from({length:129},(_,k)=>{
          const y=top+(bottom-top)*k/128;
          const r=row(Math.min(bottom-1,y))||[left,right];
          return [+y.toFixed(3),...r];
        });
        // Render continuous scanlines into one texture. This avoids SVG band
        // antialias seams and hundreds of repeated image nodes during play.
        const texture=new Image();texture.src=fit.atlasUrl;await texture.decode();
        const cloth=document.createElement('canvas');cloth.width=720;cloth.height=1280;
        const paint=cloth.getContext('2d');paint.imageSmoothingQuality='high';
        for(let yy=top;yy<bottom;yy++){
          const r=row(yy);if(!r)continue;
          const progress=(yy-top)/(bottom-top),q=progress*128,lo=Math.floor(q),hi=Math.min(128,lo+1),t=q-lo;
          const l=fit.sourceRows[lo][0]*(1-t)+fit.sourceRows[hi][0]*t;
          const rr=fit.sourceRows[lo][1]*(1-t)+fit.sourceRows[hi][1]*t;
          paint.drawImage(texture,l,fit.crop[1]+progress*fit.crop[3],Math.max(1,rr-l),fit.crop[3]/(bottom-top),r[0],yy,r[1]-r[0],1);
        }
        paint.globalCompositeOperation='destination-in';paint.drawImage(c,0,0);
        ctx.drawImage(cloth,0,0);
        result[id]={target,targetRows,encoded:c.toDataURL('image/webp',.93)};
      }
      return result;
    },source);
    const fittedDir=path.join(root,'assets/capsule/fitted');fs.mkdirSync(fittedDir,{recursive:true});
    const runtime={};
    for(const id of Object.keys(source)){
      const fit=targets[id],asset='assets/capsule/fitted/'+id+'.webp';
      fs.writeFileSync(path.join(root,asset),Buffer.from(fit.encoded.split(',')[1],'base64'));
      runtime[id]={asset,target:fit.target};
    }
    const script='// Generated by dev/build-capsule.js. Painted atlases fitted to native coverage.\n(function(root,factory){const data=factory();if(typeof module!=="undefined"&&module.exports)module.exports=data;else root.MuseCapsule=data;})(globalThis,function(){return '+JSON.stringify(runtime)+';});\n';
    fs.writeFileSync(path.join(root,'js/capsule-data.js'),script);
    console.log('Built '+Object.keys(source).length+' fitted painted pieces.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
